import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const app = resolve(root, 'pense-bem-mickey-viagem-no-tempo');
const files = ['content.js', 'data.js', 'engine.js', 'secret-codes.js', 'themes.js', 'pages.js', 'App.js'];
const source = files.map(name => readFileSync(resolve(app, name), 'utf8')
  .replace(/^import .* from ['"]\.\/.*['"];?\r?\n/gm, '')
  .replace(/export (const|function)/g, '$1')
  .replace(/require\(['"]\.\/assets\/([^'"]+)['"]\)/g, (_, asset) => {
    const bytes = readFileSync(resolve(app, 'assets', asset));
    const mime = asset.toLowerCase().endsWith('.png') ? 'image/png' : 'image/jpeg';
    return `{ uri: 'data:${mime};base64,${bytes.toString('base64')}' }`;
  })).join('\n\n');
const output = '// Generated by scripts/build-snack.mjs. Edit the modular sources.\n' + source;
const target = resolve(root, 'Snack-App.js');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Snack-App.js está desatualizado: execute npm run snack');
  console.log('Snack sincronizado com fontes e imagens.');
} else {
  writeFileSync(target, output);
  console.log(`Snack-App.js gerado: ${(Buffer.byteLength(output)/1024/1024).toFixed(1)} MiB`);
}
